-- =============================================================================
-- 01_snowflake_setup.sql  |  ASC Group Data Platform demo - account scaffolding
-- Databases (medallion), warehouses, roles (six personas + ELT admin),
-- schemas, internal stages and file formats.
-- Run as ACCOUNTADMIN (or SYSADMIN + SECURITYADMIN).
-- =============================================================================
USE ROLE ACCOUNTADMIN;

-- ---------------------------------------------------------------- warehouses
CREATE WAREHOUSE IF NOT EXISTS WH_ELT
  WAREHOUSE_SIZE = 'MEDIUM' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'ELT / orchestration compute (Bronze->Silver->Gold, reconciliation)';
CREATE WAREHOUSE IF NOT EXISTS WH_BI
  WAREHOUSE_SIZE = 'SMALL' MIN_CLUSTER_COUNT = 1 MAX_CLUSTER_COUNT = 3 SCALING_POLICY = 'STANDARD'
  AUTO_SUSPEND = 120 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Power BI DirectQuery / Import refresh and Cortex Analyst compute';

-- ---------------------------------------------------------------- databases & schemas
CREATE DATABASE IF NOT EXISTS EDW_BRONZE COMMENT = 'Raw landing - immutable source extracts with audit columns';
CREATE DATABASE IF NOT EXISTS EDW_SILVER COMMENT = 'Cleansed, de-duplicated, conformed; MDM golden records; DQ';
CREATE DATABASE IF NOT EXISTS EDW_GOLD   COMMENT = 'Certified star schema, aggregates, semantic views, controls';

CREATE SCHEMA IF NOT EXISTS EDW_BRONZE.RAW        COMMENT = 'One table per source object; columns as delivered';
CREATE SCHEMA IF NOT EXISTS EDW_BRONZE.LANDING    COMMENT = 'Stages, file formats, file-level load log';
CREATE SCHEMA IF NOT EXISTS EDW_BRONZE.QUARANTINE COMMENT = 'Rejected files and lenient landings awaiting DQ';
CREATE SCHEMA IF NOT EXISTS EDW_SILVER.CONFORMED  COMMENT = 'Conformed entities, harmonised codes, reference data';
CREATE SCHEMA IF NOT EXISTS EDW_SILVER.MDM        COMMENT = 'Master data management - vendor golden records & xref';
CREATE SCHEMA IF NOT EXISTS EDW_SILVER.DQ         COMMENT = 'Data-quality rules, results and row-level quarantine';
CREATE SCHEMA IF NOT EXISTS EDW_GOLD.STAR         COMMENT = 'Dimensions and facts (certified)';
CREATE SCHEMA IF NOT EXISTS EDW_GOLD.AGG          COMMENT = 'Pre-aggregated tables for dashboards';
CREATE SCHEMA IF NOT EXISTS EDW_GOLD.SEMANTIC     COMMENT = 'Certified measure views consumed by Power BI & Cortex Analyst';
CREATE SCHEMA IF NOT EXISTS EDW_GOLD.CONTROL      COMMENT = 'Reconciliation results, measure catalog, lineage';
CREATE SCHEMA IF NOT EXISTS EDW_GOLD.SECURITY     COMMENT = 'Persona mapping tables, row access & masking policies';

-- ---------------------------------------------------------------- file formats
CREATE OR REPLACE FILE FORMAT EDW_BRONZE.LANDING.FF_CSV_STD
  TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE NULL_IF = ('', 'NULL', 'null') TRIM_SPACE = FALSE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE DATE_FORMAT = 'YYYY-MM-DD' TIMESTAMP_FORMAT = 'YYYY-MM-DD HH24:MI:SS'
  COMMENT = 'Strict CSV: header row skipped, column-count mismatch rejects the file';

CREATE OR REPLACE FILE FORMAT EDW_BRONZE.LANDING.FF_CSV_LENIENT
  TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE NULL_IF = ('', 'NULL', 'null', 'N/A')
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
  COMMENT = 'Lenient CSV used only to land suspect files as VARCHAR for row-level DQ';

CREATE OR REPLACE FILE FORMAT EDW_BRONZE.LANDING.FF_CSV_HEADER_MATCH
  TYPE = CSV PARSE_HEADER = TRUE FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = TRUE
  COMMENT = 'Used with MATCH_BY_COLUMN_NAME for Gold seed fast-path loads';

-- ---------------------------------------------------------------- stages (internal; swap for S3/Azure external stages in production)
CREATE STAGE IF NOT EXISTS EDW_BRONZE.LANDING.STG_SOURCE_DROP
  FILE_FORMAT = EDW_BRONZE.LANDING.FF_CSV_STD DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Source extracts land here: /bronze/<object>.csv and /bad_files/<file>.csv';
CREATE STAGE IF NOT EXISTS EDW_BRONZE.LANDING.STG_QUARANTINE
  DIRECTORY = (ENABLE = TRUE) COMMENT = 'Files that failed structural validation are copied here';
CREATE STAGE IF NOT EXISTS EDW_GOLD.STAR.STG_GOLD_SEED
  FILE_FORMAT = EDW_BRONZE.LANDING.FF_CSV_HEADER_MATCH DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Gold CSV seeds for the fast-path load (09_gold_seed_fast_path.sql)';

-- File-level load log (every COPY writes a row; the orchestrator reads it)
CREATE TABLE IF NOT EXISTS EDW_BRONZE.LANDING.FILE_LOAD_LOG (
  load_id          NUMBER AUTOINCREMENT,
  loaded_at        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  src_system       VARCHAR(20),
  file_name        VARCHAR(400),
  target_table     VARCHAR(200),
  status           VARCHAR(20),          -- LOADED | REJECTED | QUARANTINED
  rows_parsed      NUMBER,
  rows_loaded      NUMBER,
  error_count      NUMBER,
  first_error      VARCHAR(2000),
  batch_id         VARCHAR(50)
);

-- ---------------------------------------------------------------- roles
CREATE ROLE IF NOT EXISTS ROLE_ELT_ADMIN       COMMENT = 'Owns pipelines; full DML on all layers';
CREATE ROLE IF NOT EXISTS ROLE_GROUP_EXEC      COMMENT = 'Persona 1: Group CEO/CFO - all entities, PII masked';
CREATE ROLE IF NOT EXISTS ROLE_FIN_ASC         COMMENT = 'Persona 2: Finance ASC B.S.C.(c) - entity ASC only';
CREATE ROLE IF NOT EXISTS ROLE_STATION_MGR     COMMENT = 'Persona 3: Station manager - own station only (BYP)';
CREATE ROLE IF NOT EXISTS ROLE_HR_BP           COMMENT = 'Persona 4: HR business partner - payroll unmasked, all entities';
CREATE ROLE IF NOT EXISTS ROLE_AIRLINE_AM      COMMENT = 'Persona 5: Airline account manager - assigned airlines only';
CREATE ROLE IF NOT EXISTS ROLE_INTERNAL_AUDIT  COMMENT = 'Persona 6: Internal audit - all layers read-only, PII hashed, controls visible';

GRANT ROLE ROLE_ELT_ADMIN      TO ROLE SYSADMIN;
GRANT ROLE ROLE_GROUP_EXEC     TO ROLE SYSADMIN;
GRANT ROLE ROLE_FIN_ASC        TO ROLE SYSADMIN;
GRANT ROLE ROLE_STATION_MGR    TO ROLE SYSADMIN;
GRANT ROLE ROLE_HR_BP          TO ROLE SYSADMIN;
GRANT ROLE ROLE_AIRLINE_AM     TO ROLE SYSADMIN;
GRANT ROLE ROLE_INTERNAL_AUDIT TO ROLE SYSADMIN;

-- warehouse usage
GRANT USAGE, OPERATE ON WAREHOUSE WH_ELT TO ROLE ROLE_ELT_ADMIN;
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE ROLE_GROUP_EXEC;
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE ROLE_FIN_ASC;
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE ROLE_STATION_MGR;
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE ROLE_HR_BP;
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE ROLE_AIRLINE_AM;
GRANT USAGE ON WAREHOUSE WH_BI TO ROLE ROLE_INTERNAL_AUDIT;
GRANT USAGE ON WAREHOUSE WH_ELT TO ROLE ROLE_INTERNAL_AUDIT;

-- ELT admin owns the three databases
GRANT OWNERSHIP ON DATABASE EDW_BRONZE TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE EDW_SILVER TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE EDW_GOLD   TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE EDW_BRONZE TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE EDW_SILVER TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE EDW_GOLD   TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
-- The stages, file formats and load log above were created as ACCOUNTADMIN; hand them over too, or
-- ROLE_ELT_ADMIN can only use them through an ACCOUNTADMIN secondary role.
GRANT OWNERSHIP ON ALL STAGES       IN SCHEMA EDW_BRONZE.LANDING TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL FILE FORMATS IN SCHEMA EDW_BRONZE.LANDING TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES       IN SCHEMA EDW_BRONZE.LANDING TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL STAGES       IN SCHEMA EDW_GOLD.STAR      TO ROLE ROLE_ELT_ADMIN COPY CURRENT GRANTS;
GRANT CREATE ROW ACCESS POLICY ON SCHEMA EDW_GOLD.SECURITY TO ROLE ROLE_ELT_ADMIN;
GRANT CREATE MASKING POLICY    ON SCHEMA EDW_GOLD.SECURITY TO ROLE ROLE_ELT_ADMIN;
GRANT APPLY ROW ACCESS POLICY ON ACCOUNT TO ROLE ROLE_ELT_ADMIN;
GRANT APPLY MASKING POLICY    ON ACCOUNT TO ROLE ROLE_ELT_ADMIN;

-- Business personas: Gold read access only (policies enforce row/column scope)
GRANT USAGE ON DATABASE EDW_GOLD TO ROLE ROLE_GROUP_EXEC;
GRANT USAGE ON DATABASE EDW_GOLD TO ROLE ROLE_FIN_ASC;
GRANT USAGE ON DATABASE EDW_GOLD TO ROLE ROLE_STATION_MGR;
GRANT USAGE ON DATABASE EDW_GOLD TO ROLE ROLE_HR_BP;
GRANT USAGE ON DATABASE EDW_GOLD TO ROLE ROLE_AIRLINE_AM;
GRANT USAGE ON DATABASE EDW_GOLD TO ROLE ROLE_INTERNAL_AUDIT;

GRANT USAGE ON ALL SCHEMAS IN DATABASE EDW_GOLD TO ROLE ROLE_GROUP_EXEC;
GRANT USAGE ON ALL SCHEMAS IN DATABASE EDW_GOLD TO ROLE ROLE_FIN_ASC;
GRANT USAGE ON ALL SCHEMAS IN DATABASE EDW_GOLD TO ROLE ROLE_STATION_MGR;
GRANT USAGE ON ALL SCHEMAS IN DATABASE EDW_GOLD TO ROLE ROLE_HR_BP;
GRANT USAGE ON ALL SCHEMAS IN DATABASE EDW_GOLD TO ROLE ROLE_AIRLINE_AM;
GRANT USAGE ON ALL SCHEMAS IN DATABASE EDW_GOLD TO ROLE ROLE_INTERNAL_AUDIT;

GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.STAR     TO ROLE ROLE_GROUP_EXEC;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.AGG      TO ROLE ROLE_GROUP_EXEC;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA EDW_GOLD.SEMANTIC TO ROLE ROLE_GROUP_EXEC;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.CONTROL  TO ROLE ROLE_GROUP_EXEC;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.STAR     TO ROLE ROLE_FIN_ASC;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.AGG      TO ROLE ROLE_FIN_ASC;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA EDW_GOLD.SEMANTIC TO ROLE ROLE_FIN_ASC;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.STAR     TO ROLE ROLE_STATION_MGR;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.AGG      TO ROLE ROLE_STATION_MGR;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA EDW_GOLD.SEMANTIC TO ROLE ROLE_STATION_MGR;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.STAR     TO ROLE ROLE_HR_BP;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.AGG      TO ROLE ROLE_HR_BP;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA EDW_GOLD.SEMANTIC TO ROLE ROLE_HR_BP;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.STAR     TO ROLE ROLE_AIRLINE_AM;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.AGG      TO ROLE ROLE_AIRLINE_AM;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA EDW_GOLD.SEMANTIC TO ROLE ROLE_AIRLINE_AM;

-- Internal audit: read everything incl. Bronze/Silver and the control tables
GRANT USAGE ON DATABASE EDW_BRONZE TO ROLE ROLE_INTERNAL_AUDIT;
GRANT USAGE ON DATABASE EDW_SILVER TO ROLE ROLE_INTERNAL_AUDIT;
GRANT USAGE ON ALL SCHEMAS IN DATABASE EDW_BRONZE TO ROLE ROLE_INTERNAL_AUDIT;
GRANT USAGE ON ALL SCHEMAS IN DATABASE EDW_SILVER TO ROLE ROLE_INTERNAL_AUDIT;
GRANT SELECT ON FUTURE TABLES IN DATABASE EDW_BRONZE TO ROLE ROLE_INTERNAL_AUDIT;
GRANT SELECT ON FUTURE TABLES IN DATABASE EDW_SILVER TO ROLE ROLE_INTERNAL_AUDIT;
GRANT SELECT ON FUTURE VIEWS  IN DATABASE EDW_SILVER TO ROLE ROLE_INTERNAL_AUDIT;
GRANT SELECT ON FUTURE TABLES IN DATABASE EDW_GOLD   TO ROLE ROLE_INTERNAL_AUDIT;
GRANT SELECT ON FUTURE VIEWS  IN DATABASE EDW_GOLD   TO ROLE ROLE_INTERNAL_AUDIT;
-- Schema-level future grants override database-level ones, so the Gold schemas that have them
-- (granted to the other personas above) need audit named explicitly or it gets nothing there.
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.STAR     TO ROLE ROLE_INTERNAL_AUDIT;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.AGG      TO ROLE ROLE_INTERNAL_AUDIT;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.CONTROL  TO ROLE ROLE_INTERNAL_AUDIT;
GRANT SELECT ON FUTURE TABLES IN SCHEMA EDW_GOLD.SEMANTIC TO ROLE ROLE_INTERNAL_AUDIT;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA EDW_GOLD.SEMANTIC TO ROLE ROLE_INTERNAL_AUDIT;
GRANT MONITOR ON ACCOUNT TO ROLE ROLE_INTERNAL_AUDIT;   -- query history / access history
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE ROLE_INTERNAL_AUDIT;

-- Cortex Analyst for personas that ask natural-language questions
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ROLE_GROUP_EXEC;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ROLE_FIN_ASC;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ROLE_AIRLINE_AM;

-- ---------------------------------------------------------------- session defaults for the demo
USE ROLE ROLE_ELT_ADMIN;
USE WAREHOUSE WH_ELT;
USE DATABASE EDW_BRONZE;
USE SCHEMA RAW;
